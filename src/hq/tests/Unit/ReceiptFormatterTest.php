<?php

use App\Support\Printing\ReceiptFormatter;

/*
| The HQ receipt preview must print exactly what the node prints: the same fixture as Pos.Tests ReceiptFixtureTests
| (docs/fixtures/receipt-format.json, `expected` generated by the C# formatter).
*/

/** @return list<array{name: string, width: int, reprint: bool, data: array<string, mixed>, expected: list<string>}> */
function receiptCases(): array
{
    $json = json_decode((string) file_get_contents(__DIR__.'/../../../../docs/fixtures/receipt-format.json'), true, flags: JSON_THROW_ON_ERROR);

    return $json['cases'];
}

it('prints every fixture case exactly like Pos.Shared', function () {
    $cases = receiptCases();
    expect($cases)->not->toBeEmpty();
    foreach ($cases as $case) {
        expect($case['expected'])->not->toBeEmpty()
            ->and(ReceiptFormatter::format($case['data'], $case['width'], $case['reprint']))->toBe($case['expected']);
    }
});

it('formats numbers like .NET "#,0.####" in id-ID', function (string $value, string $expected) {
    expect(ReceiptFormatter::number($value))->toBe($expected);
})->with([
    ['0', '0'],
    ['1250000', '1.250.000'],
    ['1250000.0000', '1.250.000'],
    ['0.5', '0,5'],
    ['-50', '-50'],
    ['-1234.5', '-1.234,5'],
    ['999', '999'],
    ['1000', '1.000'],
    ['0.0001', '0,0001'],
]);

it('builds header and footer from the settings, skipping empty fields', function () {
    expect(ReceiptFormatter::header(' TOKO A ', '', null, '0812'))->toBe(['TOKO A', 'Telp. 0812'])
        ->and(ReceiptFormatter::header(null, null, null, '  '))->toBe([])
        ->and(ReceiptFormatter::footer('Terima kasih', ' '))->toBe(['Terima kasih']);
});

it('never prints a line wider than the paper', function () {
    foreach (receiptCases() as $case) {
        foreach (ReceiptFormatter::format($case['data'], $case['width']) as $line) {
            expect(mb_strlen($line))->toBeLessThanOrEqual($case['width']);
        }
    }
});
