/// <summary>
/// Creates a sale in ONE transaction (re-run on deadlock): sales, sale_lines, sale_payments, FEFO stock
/// posting (doc_type SALE) and the outbox row. Prices come from the server, never from the client.
/// Idempotent on the client-generated sale id. Promotions and tax: TODO (tax_amount = 0).
/// </summary>
public sealed class SaleService(TransactionRunner runner, NodeIdentity nodeIdentity, TimeProvider clock, SaleHooks? hooks = null)
{
    /// <param name="deviceId">The device the request came from (header X-Device-Id).</param>
    /// <param name="userId">The logged-in cashier; stored as <c>created_by</c>.</param>
    /// <param name="canUseAnyShift">Permission <c>shift.share</c>: may sell on a shift opened by another user.</param>
    public async Task<CreateSaleResult> CreateAsync(
        CreateSaleRequest request, Guid deviceId, Guid userId, bool canUseAnyShift = false,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Id.Version != 7)
            throw ApiException.Unprocessable("invalid_id", "The sale id must be a UUID v7 generated by the client.");
        if (request.Lines is not { Count: > 0 })
            throw ApiException.Unprocessable("no_lines", "A sale needs at least one line.");

        var node = await nodeIdentity.GetAsync(cancellationToken);

        var stored = await TryLoadAsync(request.Id, cancellationToken);
        if (stored is not null)
            return new CreateSaleResult(stored, [], Replayed: true);

        try
        {
            return await runner.RunAsync((c, tx, ct) => CreateWithinAsync(c, tx, node, request, deviceId, userId, canUseAnyShift, ct),
                "Create sale", cancellationToken);
        }
        catch (MySqlException ex) when (ex.ErrorCode == MySqlErrorCode.DuplicateKeyEntry)
        {
            // The same id was being saved concurrently; the other request won and this one rolled back.
            stored = await TryLoadAsync(request.Id, cancellationToken);
            if (stored is null)
                throw;
            return new CreateSaleResult(stored, [], Replayed: true);
        }
    }

    public async Task<SaleDto?> TryLoadAsync(Guid id, CancellationToken cancellationToken = default)
    {
        await using var connection = await runner.ConnectionFactory.OpenAsync(cancellationToken);
        return await LoadAsync(connection, null, id, cancellationToken);
    }

    private async Task<CreateSaleResult> CreateWithinAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, CreateSaleRequest request, Guid deviceId, Guid userId,
        bool canUseAnyShift, CancellationToken ct)
    {
        var lines = request.Lines!;
        var payments = request.Payments ?? [];

        // Shared lock: a shift close (FOR UPDATE) waits until this sale commits.
        var shift = await c.QuerySingleOrDefaultAsync<(Guid Id, Guid CashierId, string Number)?>(new CommandDefinition(
            "SELECT id, cashier_id, number FROM cashier_shifts WHERE device_id = @deviceId AND node_id = @nodeId AND status = @open FOR SHARE",
            new { deviceId, nodeId = node.Id, open = ShiftStatus.Open }, tx, cancellationToken: ct))
            ?? throw ApiException.Conflict("no_open_shift", $"Device {deviceId} has no open shift.");
        if (shift.CashierId != userId && !canUseAnyShift)
            throw new ApiException(StatusCodes.Status403Forbidden, "not_shift_owner",
                $"Shift {shift.Number} belongs to another cashier; close it and open your own shift.");
        var shiftId = shift.Id;

        var customer = request.CustomerId is { } customerId
            ? await c.QuerySingleOrDefaultAsync<CustomerRow>(new CommandDefinition(
                  """
                  SELECT credit_limit AS CreditLimit, payment_term_days AS PaymentTermDays FROM contacts
                  WHERE id = @customerId AND is_customer = 1 AND is_active = 1 AND deleted_at IS NULL
                  """, new { customerId }, tx, cancellationToken: ct))
              ?? throw ApiException.Unprocessable("unknown_customer", $"Customer {customerId} does not exist.")
            : null;

        var settings = await LoadSettingsAsync(c, tx, node.BranchId, ct);
        var methods = await ResolvePaymentMethodsAsync(c, tx, payments, ct);
        var locationId = await ResolveLocationAsync(c, tx, node, request.LocationId, ct);
        var soldAt = clock.GetUtcNow().UtcDateTime;

        var resolved = new List<ResolvedLine>();
        foreach (var line in lines)
            resolved.Add(await ResolveLineAsync(c, tx, node, line, soldAt, settings.CurrencyDecimals, ct));

        var totals = Validate(() => SaleCalculator.Calculate(
            resolved.Select(l => l.Amounts.LineTotal).ToList(),
            payments.Select((p, i) => new PaymentInput(methods[i].Kind, p.Amount)).ToList(),
            settings.Rounding,
            customer is not null));

        var warnings = new List<SaleWarning>();
        if (totals.CreditAmount > 0)
        {
            var outstanding = await OutstandingCreditAsync(c, tx, request.CustomerId!.Value, ct);
            var check = Validate(() => CreditCheck.Evaluate(customer!.CreditLimit, outstanding, totals.CreditAmount));
            if (check.LimitExceeded)
                warnings.Add(new SaleWarning("credit_limit_exceeded",
                    $"Customer credit {check.OutstandingAfter} exceeds the limit {customer!.CreditLimit} by {check.ExceededBy}."));
        }

        var saleId = request.Id;
        var lineIds = resolved.Select(_ => Guid.CreateVersion7()).ToList();

        await StockPostingService.PostWithinAsync(c, tx,
            resolved.Select((l, i) => new StockMovement(
                new StockDocumentLine(node.Id, locationId, l.ProductId, StockDocTypes.Sale, saleId, lineIds[i], soldAt),
                StockDirection.Out, l.BaseQty)).ToList(), ct);
        await Step(SaleSteps.StockPosted, ct);

        // Taken late: the sequence row is shared by every sale of the month.
        var number = await DocumentNumbering.NextAsync(c, tx, node, DocumentTypes.Sale, soldAt, ct);
        await Step(SaleSteps.Numbered, ct);

        DateTime? dueDate = totals.CreditAmount > 0 && customer?.PaymentTermDays is { } term
            ? BranchClock.Today(soldAt, node.TimeZone).AddDays(term).ToDateTime(TimeOnly.MinValue, DateTimeKind.Utc)
            : null;

        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO sales (id, node_id, number, shift_id, customer_id, sold_at, subtotal, discount_amount, tax_amount,
                               rounding_amount, total, credit_amount, due_date, notes, created_by)
            VALUES (@saleId, @nodeId, @number, @shiftId, @CustomerId, @soldAt, @Subtotal, 0, 0,
                    @RoundingAmount, @Total, @CreditAmount, @dueDate, @Notes, @createdBy)
            """,
            new
            {
                saleId, nodeId = node.Id, number, shiftId, request.CustomerId, soldAt,
                totals.Subtotal, totals.RoundingAmount, totals.Total, totals.CreditAmount, dueDate, request.Notes,
                createdBy = userId,
            }, tx, cancellationToken: ct));

        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO sale_lines (id, sale_id, line_no, product_id, product_unit_id, location_id, qty, conversion, base_qty,
                                    unit_price, discount_amount, tax_amount, line_total)
            VALUES (@Id, @saleId, @LineNo, @ProductId, @ProductUnitId, @locationId, @Qty, @Conversion, @BaseQty,
                    @UnitPrice, @DiscountAmount, 0, @LineTotal)
            """,
            resolved.Select((l, i) => new
            {
                Id = lineIds[i], saleId, LineNo = i + 1, l.ProductId, l.ProductUnitId, locationId, l.Qty, l.Conversion, l.BaseQty,
                l.UnitPrice, l.Amounts.DiscountAmount, l.Amounts.LineTotal,
            }).ToList(), tx, cancellationToken: ct));

        if (payments.Count > 0)
        {
            await c.ExecuteAsync(new CommandDefinition(
                """
                INSERT INTO sale_payments (id, sale_id, payment_method_id, amount, tendered, change_given, reference)
                VALUES (@Id, @saleId, @MethodId, @Applied, @Tendered, @ChangeGiven, @Reference)
                """,
                payments.Select((p, i) => new
                {
                    Id = Guid.CreateVersion7(), saleId, MethodId = methods[i].Id, totals.Payments[i].Applied,
                    totals.Payments[i].Tendered, totals.Payments[i].ChangeGiven, p.Reference,
                }).ToList(), tx, cancellationToken: ct));
        }
        await Step(SaleSteps.SaleInserted, ct);

        var sale = await LoadAsync(c, tx, saleId, ct)
            ?? throw new InvalidOperationException($"Sale {saleId} was not found after insert.");
        await OutboxWriter.WriteAsync(c, tx, SyncDocTypes.Sale, saleId, 1, sale, ct);
        await Step(SaleSteps.OutboxWritten, ct);

        return new CreateSaleResult(sale, warnings, Replayed: false);
    }

    private Task Step(string step, CancellationToken ct) => hooks?.AfterStep?.Invoke(step, ct) ?? Task.CompletedTask;

    private static T Validate<T>(Func<T> calculate)
    {
        try
        {
            return calculate();
        }
        catch (SaleValidationException ex)
        {
            throw ApiException.Unprocessable(ex.Code, ex.Message);
        }
    }

    // ---- resolution ---------------------------------------------------------------------------

    private static async Task<ResolvedLine> ResolveLineAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, SaleLineRequest line, DateTime now, int currencyDecimals,
        CancellationToken ct)
    {
        if ((line.ProductUnitId is null) == string.IsNullOrWhiteSpace(line.Barcode))
            throw ApiException.Unprocessable("invalid_line", "Each line needs exactly one of product_unit_id or barcode.");
        if (line.Qty <= 0)
            throw ApiException.Unprocessable("invalid_quantity", "Quantity must be greater than zero.");

        var productUnitId = line.ProductUnitId
            ?? await c.QuerySingleOrDefaultAsync<Guid?>(new CommandDefinition(
                "SELECT product_unit_id FROM product_barcodes WHERE barcode = @Barcode AND deleted_at IS NULL",
                new { line.Barcode }, tx, cancellationToken: ct))
            ?? throw ApiException.Unprocessable("unknown_barcode", $"Barcode '{line.Barcode}' is not registered.");

        var unit = await c.QuerySingleOrDefaultAsync<UnitRow>(new CommandDefinition(
            """
            SELECT pu.product_id AS ProductId, pu.conversion AS Conversion, u.allow_decimal AS AllowDecimal
            FROM product_units pu
            JOIN products p ON p.id = pu.product_id
            JOIN units u ON u.id = pu.unit_id
            WHERE pu.id = @productUnitId AND pu.deleted_at IS NULL AND p.deleted_at IS NULL
            """, new { productUnitId }, tx, cancellationToken: ct))
            ?? throw ApiException.Unprocessable("unknown_product_unit", $"Product unit {productUnitId} does not exist.");

        var baseQty = UnitConversion.ToBaseQty(line.Qty, unit.Conversion, unit.AllowDecimal);

        var candidates = await c.QueryAsync<PriceCandidate>(new CommandDefinition(
            """
            SELECT branch_id AS BranchId, price AS Price, min_qty AS MinQty, effective_from AS EffectiveFrom
            FROM prices
            WHERE product_unit_id = @productUnitId AND deleted_at IS NULL AND (branch_id = @branchId OR branch_id IS NULL)
            """, new { productUnitId, branchId = node.BranchId }, tx, cancellationToken: ct));
        var price = PriceResolver.Resolve(candidates, node.BranchId, now, line.Qty)
            ?? throw ApiException.Unprocessable("no_price", $"Product unit {productUnitId} has no price for quantity {line.Qty}.");

        SaleLineAmounts amounts;
        try
        {
            amounts = SaleLineCalculator.Calculate(line.Qty, price, line.DiscountPct, line.DiscountAmount, currencyDecimals);
        }
        catch (ArgumentOutOfRangeException ex)
        {
            throw ApiException.Unprocessable("invalid_discount", ex.Message);
        }

        return new ResolvedLine(unit.ProductId, productUnitId, line.Qty, unit.Conversion, baseQty, price, amounts);
    }

    private static async Task<IReadOnlyList<MethodRow>> ResolvePaymentMethodsAsync(
        MySqlConnection c, MySqlTransaction tx, IReadOnlyList<SalePaymentRequest> payments, CancellationToken ct)
    {
        var codes = payments.Select(p => (p.Method ?? "").Trim().ToUpperInvariant()).ToList();
        var known = (await c.QueryAsync<MethodRow>(new CommandDefinition(
                """
                SELECT id AS Id, code AS Code, is_cash AS IsCash, is_credit AS IsCredit FROM payment_methods
                WHERE code IN @codes AND is_active = 1 AND deleted_at IS NULL
                """, new { codes = codes.DefaultIfEmpty("").ToList() }, tx, cancellationToken: ct)))
            .ToDictionary(m => m.Code, StringComparer.OrdinalIgnoreCase);

        return codes.Select(code => known.TryGetValue(code, out var method)
                ? method
                : throw ApiException.Unprocessable("unknown_payment_method", $"Payment method '{code}' is not available."))
            .ToList();
    }

    private static async Task<Guid> ResolveLocationAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, Guid? requested, CancellationToken ct)
    {
        var sellable = (await c.QueryAsync<Guid>(new CommandDefinition(
            "SELECT id FROM locations WHERE node_id = @nodeId AND is_sellable = 1 AND is_active = 1 AND deleted_at IS NULL",
            new { nodeId = node.Id }, tx, cancellationToken: ct))).ToList();

        if (requested is { } id)
            return sellable.Contains(id)
                ? id
                : throw ApiException.Unprocessable("location_not_sellable", $"Location {id} is not a sellable location of node {node.Code}.");

        return sellable.Count switch
        {
            1 => sellable[0],
            0 => throw ApiException.Unprocessable("no_sellable_location", $"Node {node.Code} has no sellable location."),
            _ => throw ApiException.Unprocessable("location_required", "This node has several sellable locations; send location_id."),
        };
    }

    private static async Task<SaleSettings> LoadSettingsAsync(MySqlConnection c, MySqlTransaction tx, Guid branchId, CancellationToken ct)
    {
        // Branch row first, then the global row (branch_id NULL).
        var rows = await c.QueryAsync<(string Key, string Value)>(new CommandDefinition(
            """
            SELECT setting_key, CAST(setting_value AS CHAR) FROM settings
            WHERE setting_key IN ('rounding.cash_step', 'rounding.cash_mode', 'currency.decimals')
              AND deleted_at IS NULL AND (branch_id = @branchId OR branch_id IS NULL)
            ORDER BY branch_id IS NULL
            """, new { branchId }, tx, cancellationToken: ct));
        var values = rows.GroupBy(r => r.Key).ToDictionary(g => g.Key, g => g.First().Value);

        var step = values.TryGetValue("rounding.cash_step", out var s) ? JsonDecimal(s) : 0m;
        var mode = values.TryGetValue("rounding.cash_mode", out var m) ? CashRoundingModes.Parse(JsonString(m)) : CashRoundingMode.Nearest;
        var decimals = values.TryGetValue("currency.decimals", out var d) ? (int)JsonDecimal(d) : Rupiah.DefaultCurrencyDecimals;
        return new SaleSettings(new CashRoundingSettings(step, mode), decimals);
    }

    private static decimal JsonDecimal(string json)
    {
        using var doc = JsonDocument.Parse(json);
        return doc.RootElement.ValueKind == JsonValueKind.String
            ? decimal.Parse(doc.RootElement.GetString()!, NumberStyles.Number, CultureInfo.InvariantCulture)
            : doc.RootElement.GetDecimal();
    }

    private static string JsonString(string json)
    {
        using var doc = JsonDocument.Parse(json);
        return doc.RootElement.GetString() ?? "";
    }

    /// <summary>Local view only: credit of non-voided sales minus receivable payments recorded at this node.</summary>
    private static Task<decimal> OutstandingCreditAsync(MySqlConnection c, MySqlTransaction tx, Guid customerId, CancellationToken ct) =>
        c.ExecuteScalarAsync<decimal>(new CommandDefinition(
            """
            SELECT COALESCE((SELECT SUM(s.credit_amount) FROM sales s
                             WHERE s.customer_id = @customerId
                               AND NOT EXISTS (SELECT 1 FROM sale_voids v WHERE v.sale_id = s.id)), 0)
                 - COALESCE((SELECT SUM(rp.amount) FROM receivable_payments rp WHERE rp.customer_id = @customerId), 0)
            """, new { customerId }, tx, cancellationToken: ct));

