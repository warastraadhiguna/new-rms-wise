-- =====================================================================
-- Multi-branch synchronized POS - database schema (draft v3, 2026-11-20)
-- MySQL 8.4 LTS, InnoDB, utf8mb4
--
-- Part A  Organization & master data      : owner HQ, pulled by every node
-- Part B  HQ documents pulled by nodes    : purchase orders, stock count approvals
-- Part C  Node documents                  : owner = the node in node_id, pushed to HQ
-- Part D  Sync & local-only data          : node only
-- Part E  HQ only                         : purchasing, payables, accounting, audit, sync intake
--
-- Design rules
--  1. Single writer. Every row has exactly one owner: HQ for master data (Part A/B),
--     the node in node_id for node documents (Part C). Nobody else ever writes that row.
--  2. Replicas. A node may hold read-only copies of other nodes' documents
--     (e.g. a customer's recent sales from another store, for returns and credit payments).
--     A node only pushes rows where node_id = its own node.
--  3. Ids. Synced tables: UUID v7 as CHAR(36) ASCII, generated by the owner.
--     Local-only and HQ-internal tables: BIGINT AUTO_INCREMENT.
--     Users see document numbers (TK01-SL-202611-000123), never UUIDs.
--     Codes created at a node (customers, temporary products) are prefixed with the node code.
--  4. Master data is never hard-deleted: deleted_at + a new version, so nodes see deletions.
--  5. Documents are never deleted. Corrections are new documents (void, return, adjustment).
--     Documents that change after creation carry row_version; HQ keeps the highest version.
--  6. All DATETIME columns are UTC. Event times come from the Node Service clock, not client PCs.
--  7. Money and quantities: DECIMAL(18,4). Stock is always counted in the product's base unit.
--  8. Status and type columns are VARCHAR (values listed in comments, enforced by the app),
--     so adding a value needs an app update, not an ALTER TABLE on every node.
--  9. Stock by expiry date lives in stock_ledger. The Node Service allocates sales FEFO;
--     one sale line can produce several ledger rows with different expiry dates.
-- =====================================================================

SET NAMES utf8mb4;

-- =====================================================================
-- PART A. ORGANIZATION & MASTER DATA  (owner: HQ, pulled by nodes via version)
-- =====================================================================

CREATE TABLE entities (                                  -- legal entity, owns the general ledger
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(20)  NOT NULL,
  name          VARCHAR(200) NOT NULL,
  address       TEXT         NULL,
  tax_id        VARCHAR(30)  NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_entities_code (code),
  KEY ix_entities_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE branches (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  entity_id     CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(20)  NOT NULL,
  name          VARCHAR(200) NOT NULL,
  address       TEXT         NULL,
  timezone      VARCHAR(40)  NOT NULL DEFAULT 'Asia/Jakarta',  -- for display and daily reports
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_branches_code (code),
  KEY ix_branches_version (version),
  CONSTRAINT fk_branches_entity FOREIGN KEY (entity_id) REFERENCES entities (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- A node is a physical site with its own database. HQ is also a node (type HQ).
CREATE TABLE nodes (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  branch_id     CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(10)  NOT NULL,                 -- TK01, GD01, GD02
  name          VARCHAR(200) NOT NULL,
  type          VARCHAR(20)  NOT NULL,                 -- HQ | STORE | WAREHOUSE
  address       TEXT         NULL,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_nodes_code (code),
  KEY ix_nodes_version (version),
  CONSTRAINT fk_nodes_branch FOREIGN KEY (branch_id) REFERENCES branches (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Stock locations inside a node. Only the owning node writes ledger rows for them.
CREATE TABLE locations (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  node_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(20)  NOT NULL,                 -- DISPLAY, STORAGE, RACK-A, DAMAGED
  name          VARCHAR(100) NOT NULL,
  type          VARCHAR(20)  NOT NULL,                 -- DISPLAY | STORAGE | DAMAGED
  is_sellable   TINYINT(1)   NOT NULL DEFAULT 0,      -- cashiers sell only from sellable locations
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_locations_node_code (node_id, code),
  KEY ix_locations_version (version),
  CONSTRAINT fk_locations_node FOREIGN KEY (node_id) REFERENCES nodes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE roles (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(30)  NOT NULL,                 -- CASHIER, STORE_ADMIN, WAREHOUSE_STAFF, HQ_ADMIN, ACCOUNTANT, OWNER
  name          VARCHAR(100) NOT NULL,
  permissions   JSON         NULL,                     -- ["sale.void","discount.max:10",...]
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_roles_code (code),
  KEY ix_roles_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Password/PIN hashes are replicated to nodes so staff can log in offline.
CREATE TABLE users (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(255) NOT NULL,                 -- argon2id / bcrypt
  pin_hash      VARCHAR(255) NULL,                     -- quick cashier login
  full_name     VARCHAR(200) NOT NULL,
  phone         VARCHAR(20)  NULL,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_users_username (username),
  KEY ix_users_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE user_roles (                              -- node_id NULL = all nodes
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  user_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  role_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  node_id       CHAR(36) CHARACTER SET ascii NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_user_roles_user (user_id),
  KEY ix_user_roles_version (version),
  CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id),
  CONSTRAINT fk_user_roles_node FOREIGN KEY (node_id) REFERENCES nodes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE devices (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  node_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  name          VARCHAR(100) NOT NULL,                 -- "Cashier PC 2"
  type          VARCHAR(20)  NOT NULL,                 -- NODE_SERVER | CASHIER_PC | ADMIN_PC | ANDROID
  fingerprint   VARCHAR(128) NOT NULL,
  public_key    TEXT         NOT NULL,
  status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING',  -- PENDING | ACTIVE | REVOKED
  approved_by   CHAR(36) CHARACTER SET ascii NULL,
  approved_at   DATETIME(3)  NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_devices_node (node_id),
  KEY ix_devices_version (version),
  CONSTRAINT fk_devices_node FOREIGN KEY (node_id) REFERENCES nodes (id),
  CONSTRAINT fk_devices_approved_by FOREIGN KEY (approved_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE brands (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  name          VARCHAR(200) NOT NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_brands_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE categories (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  parent_id     CHAR(36) CHARACTER SET ascii NULL,
  name          VARCHAR(200) NOT NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_categories_version (version),
  CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE units (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(20)  NOT NULL,                 -- PCS, BOX, DOZEN, KG
  name          VARCHAR(50)  NOT NULL,
  allow_decimal TINYINT(1)   NOT NULL DEFAULT 0,      -- KG can be 0.25, PCS cannot
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_units_code (code),
  KEY ix_units_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE products (
  id                 CHAR(36) CHARACTER SET ascii NOT NULL,
  sku                VARCHAR(40)  NOT NULL,            -- temporary products: <node code>-T0001
  name               VARCHAR(200) NOT NULL,
  brand_id           CHAR(36) CHARACTER SET ascii NULL,
  category_id        CHAR(36) CHARACTER SET ascii NULL,
  base_unit_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  track_expiry       TINYINT(1)   NOT NULL DEFAULT 0,
  min_stock          DECIMAL(18,4) NULL,               -- reorder warning, base units
  status             VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE | INACTIVE | TEMPORARY
  created_at_node_id CHAR(36) CHARACTER SET ascii NULL,       -- set for TEMPORARY products
  merged_into_id     CHAR(36) CHARACTER SET ascii NULL,       -- official product replacing a TEMPORARY one
  version            BIGINT       NOT NULL DEFAULT 0,
  deleted_at         DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_products_sku (sku),
  KEY ix_products_name (name),
  KEY ix_products_version (version),
  CONSTRAINT fk_products_brand    FOREIGN KEY (brand_id)           REFERENCES brands (id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id)        REFERENCES categories (id),
  CONSTRAINT fk_products_unit     FOREIGN KEY (base_unit_id)       REFERENCES units (id),
  CONSTRAINT fk_products_node     FOREIGN KEY (created_at_node_id) REFERENCES nodes (id),
  CONSTRAINT fk_products_merged   FOREIGN KEY (merged_into_id)     REFERENCES products (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Selling/purchasing units per product with conversion to the base unit.
CREATE TABLE product_units (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  product_id    CHAR(36) CHARACTER SET ascii NOT NULL,
  unit_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  conversion    DECIMAL(18,4) NOT NULL DEFAULT 1,      -- 1 BOX = 24 PCS -> 24
  is_default_sale     TINYINT(1) NOT NULL DEFAULT 0,
  is_default_purchase TINYINT(1) NOT NULL DEFAULT 0,
  sort_order    SMALLINT      NOT NULL DEFAULT 0,
  version       BIGINT        NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)   NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_units (product_id, unit_id),
  KEY ix_product_units_version (version),
  CONSTRAINT fk_product_units_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT fk_product_units_unit    FOREIGN KEY (unit_id)    REFERENCES units (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Several barcodes per product unit (supplier changes packaging, internal labels).
CREATE TABLE product_barcodes (
  id              CHAR(36) CHARACTER SET ascii NOT NULL,
  product_unit_id CHAR(36) CHARACTER SET ascii NOT NULL,
  barcode         VARCHAR(50)  NOT NULL,
  version         BIGINT       NOT NULL DEFAULT 0,
  deleted_at      DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_barcodes (barcode),
  KEY ix_product_barcodes_version (version),
  CONSTRAINT fk_product_barcodes_pu FOREIGN KEY (product_unit_id) REFERENCES product_units (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Price list with history. branch_id NULL = default price for all branches.
-- Current price = latest effective_from <= now, branch row before default row.
CREATE TABLE prices (
  id              CHAR(36) CHARACTER SET ascii NOT NULL,
  product_unit_id CHAR(36) CHARACTER SET ascii NOT NULL,
  branch_id       CHAR(36) CHARACTER SET ascii NULL,
  price           DECIMAL(18,4) NOT NULL,
  min_qty         DECIMAL(18,4) NOT NULL DEFAULT 1,     -- tiered/wholesale price
  effective_from  DATETIME(3)   NOT NULL,
  created_by      CHAR(36) CHARACTER SET ascii NOT NULL,
  version         BIGINT        NOT NULL DEFAULT 0,
  deleted_at      DATETIME(3)   NULL,
  PRIMARY KEY (id),
  KEY ix_prices_lookup (product_unit_id, branch_id, effective_from),
  KEY ix_prices_version (version),
  CONSTRAINT fk_prices_pu     FOREIGN KEY (product_unit_id) REFERENCES product_units (id),
  CONSTRAINT fk_prices_branch FOREIGN KEY (branch_id)       REFERENCES branches (id),
  CONSTRAINT fk_prices_user   FOREIGN KEY (created_by)      REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Discounts as rules instead of fixed columns (covers brand discount, product discount, period promos).
CREATE TABLE promotions (
  id              CHAR(36) CHARACTER SET ascii NOT NULL,
  name            VARCHAR(200)  NOT NULL,
  scope           VARCHAR(20)   NOT NULL,              -- PRODUCT | BRAND | CATEGORY | ALL
  scope_id        CHAR(36) CHARACTER SET ascii NULL,   -- id of product/brand/category; NULL for ALL
  branch_id       CHAR(36) CHARACTER SET ascii NULL,   -- NULL = all branches
  discount_pct    DECIMAL(9,4)  NOT NULL DEFAULT 0,
  discount_amount DECIMAL(18,4) NOT NULL DEFAULT 0,    -- per base unit
  min_qty         DECIMAL(18,4) NOT NULL DEFAULT 0,
  priority        SMALLINT      NOT NULL DEFAULT 0,    -- order when several promotions apply
  is_stackable    TINYINT(1)    NOT NULL DEFAULT 0,
  starts_at       DATETIME(3)   NOT NULL,
  ends_at         DATETIME(3)   NULL,
  version         BIGINT        NOT NULL DEFAULT 0,
  deleted_at      DATETIME(3)   NULL,
  PRIMARY KEY (id),
  KEY ix_promotions_scope (scope, scope_id),
  KEY ix_promotions_version (version),
  CONSTRAINT fk_promotions_branch FOREIGN KEY (branch_id) REFERENCES branches (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Customers and suppliers. Customers may be registered at a node (code prefixed with node code).
-- Owner is HQ once pushed; a node-created contact is owned by that node until HQ adopts it.
CREATE TABLE contacts (
  id                 CHAR(36) CHARACTER SET ascii NOT NULL,
  code               VARCHAR(30)  NOT NULL,            -- C000123, or TK01-C0001 when created at a node
  is_customer        TINYINT(1)   NOT NULL DEFAULT 0,
  is_supplier        TINYINT(1)   NOT NULL DEFAULT 0,
  name               VARCHAR(300) NOT NULL,
  company_name       VARCHAR(200) NULL,
  address            TEXT         NULL,
  email              VARCHAR(200) NULL,
  phone              VARCHAR(50)  NULL,
  tax_id             VARCHAR(30)  NULL,
  credit_limit       DECIMAL(18,4) NULL,               -- customers; NULL = no credit sales
  payment_term_days  SMALLINT     NULL,
  bank_account       TEXT         NULL,                -- suppliers
  is_active          TINYINT(1)   NOT NULL DEFAULT 1,
  created_at_node_id CHAR(36) CHARACTER SET ascii NULL,
  version            BIGINT       NOT NULL DEFAULT 0,
  deleted_at         DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_contacts_code (code),
  KEY ix_contacts_name (name),
  KEY ix_contacts_phone (phone),
  KEY ix_contacts_version (version),
  CONSTRAINT fk_contacts_node FOREIGN KEY (created_at_node_id) REFERENCES nodes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sales_reps (                              -- supplier sales representatives
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  supplier_id   CHAR(36) CHARACTER SET ascii NOT NULL,
  name          VARCHAR(250) NOT NULL,
  phone         VARCHAR(50)  NULL,
  notes         TEXT         NULL,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_sales_reps_version (version),
  CONSTRAINT fk_sales_reps_supplier FOREIGN KEY (supplier_id) REFERENCES contacts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE supplier_products (                       -- which supplier (and rep) carries which product
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  supplier_id   CHAR(36) CHARACTER SET ascii NOT NULL,
  product_id    CHAR(36) CHARACTER SET ascii NOT NULL,
  sales_rep_id  CHAR(36) CHARACTER SET ascii NULL,
  supplier_sku  VARCHAR(50)  NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_supplier_products (supplier_id, product_id),
  KEY ix_supplier_products_version (version),
  CONSTRAINT fk_sp_supplier FOREIGN KEY (supplier_id)  REFERENCES contacts (id),
  CONSTRAINT fk_sp_product  FOREIGN KEY (product_id)   REFERENCES products (id),
  CONSTRAINT fk_sp_rep      FOREIGN KEY (sales_rep_id) REFERENCES sales_reps (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE payment_methods (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  code          VARCHAR(20)  NOT NULL,                 -- CASH, TRANSFER, QRIS, DEBIT, CREDIT
  name          VARCHAR(50)  NOT NULL,
  is_cash       TINYINT(1)   NOT NULL DEFAULT 0,      -- counts toward the cash drawer
  is_credit     TINYINT(1)   NOT NULL DEFAULT 0,      -- creates a receivable
  account_code  VARCHAR(20)  NULL,                     -- GL account used by posting
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_payment_methods_code (code),
  KEY ix_payment_methods_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE reasons (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  type          VARCHAR(20)  NOT NULL,                 -- SALE_VOID | ADJUSTMENT | RETURN
  name          VARCHAR(100) NOT NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_reasons_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE expense_types (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  name          VARCHAR(200) NOT NULL,
  account_code  VARCHAR(20)  NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_expense_types_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Key/value settings. branch_id NULL = global. Values are JSON so types stay explicit.
-- Examples: receipt.footer, tax.vat_pct, tax.prices_include_vat, rounding.cash_step,
-- loyalty.points_per_amount, loyalty.min_redeem, returns.window_days, sync.alert_minutes, price_code.map
CREATE TABLE settings (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  branch_id     CHAR(36) CHARACTER SET ascii NULL,
  setting_key   VARCHAR(60)  NOT NULL,
  setting_value JSON         NOT NULL,
  version       BIGINT       NOT NULL DEFAULT 0,
  deleted_at    DATETIME(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_settings (branch_id, setting_key),
  KEY ix_settings_version (version),
  CONSTRAINT fk_settings_branch FOREIGN KEY (branch_id) REFERENCES branches (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


-- =====================================================================
-- PART B. HQ DOCUMENTS PULLED BY NODES  (owner: HQ)
-- =====================================================================

CREATE TABLE purchase_orders (
  id              CHAR(36) CHARACTER SET ascii NOT NULL,
  number          VARCHAR(40)   NOT NULL,
  supplier_id     CHAR(36) CHARACTER SET ascii NOT NULL,
