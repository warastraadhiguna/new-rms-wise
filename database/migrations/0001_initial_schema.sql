  CONSTRAINT fk_po_user     FOREIGN KEY (created_by)     REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE purchase_order_lines (
  id                CHAR(36) CHARACTER SET ascii NOT NULL,
  purchase_order_id CHAR(36) CHARACTER SET ascii NOT NULL,
  line_no           SMALLINT      NOT NULL,
  product_id        CHAR(36) CHARACTER SET ascii NOT NULL,
  product_unit_id   CHAR(36) CHARACTER SET ascii NOT NULL,
  qty               DECIMAL(18,4) NOT NULL,
  conversion        DECIMAL(18,4) NOT NULL,
  unit_price        DECIMAL(18,4) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_pol_line (purchase_order_id, line_no),
