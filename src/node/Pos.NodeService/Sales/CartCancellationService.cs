namespace Pos.NodeService.Sales;

/// <param name="Id">UUID v7 created by the client; sending it again returns the stored document.</param>
/// <param name="Reason">Why the cart was cancelled (required, as in RMS 2).</param>
/// <param name="TotalAmount">Cart total as shown to the cashier.</param>
public sealed record CartCancellationRequest(
    Guid Id,
    string? Reason,
    decimal TotalAmount,
    IReadOnlyList<CartCancellationLineRequest>? Lines);

/// <summary>A cart line as shown when it was cancelled (unit and price are what the cashier saw).</summary>
public sealed record CartCancellationLineRequest(Guid ProductUnitId, decimal Qty, decimal UnitPrice, decimal LineTotal);

public sealed record CartCancellationDto(
    Guid Id,
    Guid NodeId,
    string Number,
    Guid ShiftId,
    Guid DeviceId,
    Guid CashierId,
    DateTime CancelledAt,
    string Reason,
    decimal TotalAmount,
    IReadOnlyList<CartCancellationLineDto> Lines);

public sealed record CartCancellationLineDto(
    Guid Id, int LineNo, Guid ProductId, Guid ProductUnitId, decimal Qty, decimal UnitPrice, decimal LineTotal);

public sealed record CartCancellationResult(CartCancellationDto Cancellation, bool Replayed);

/// <summary>
/// F12 "Batal": records a cancelled, unpaid cart with the cashier's reason (RMS 2 FormKeteranganBatalTransaksi).
/// A node document with its own number (BT) and outbox row; no effect on stock.
/// The same shift rules as sales apply: an open shift on the device, owned by the user unless shift.share.
/// </summary>
public sealed class CartCancellationService(TransactionRunner runner, NodeIdentity nodeIdentity, TimeProvider clock)
{
    public async Task<CartCancellationResult> CreateAsync(
        CartCancellationRequest request, Guid deviceId, Guid userId, PermissionSet permissions, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Id.Version != 7)
            throw ApiException.Unprocessable("invalid_id", "The id must be a UUID v7 generated by the client.");
        var reason = (request.Reason ?? "").Trim();
        if (reason.Length == 0)
            throw ApiException.Unprocessable("reason_required", "Fill in why the transaction is cancelled.");
        if (request.Lines is not { Count: > 0 })
            throw ApiException.Unprocessable("no_lines", "There is nothing to cancel.");
        if (request.Lines.Any(l => l.Qty <= 0))
            throw ApiException.Unprocessable("invalid_quantity", "Quantities must be greater than zero.");

        var node = await nodeIdentity.GetAsync(ct);
        if (await TryLoadAsync(request.Id, ct) is { } stored)
            return new CartCancellationResult(stored, Replayed: true);

        try
        {
            var created = await runner.RunAsync((c, tx, token) =>
                CreateWithinAsync(c, tx, node, request, reason, deviceId, userId, permissions, token), "Cancel cart", ct);
            return new CartCancellationResult(created, Replayed: false);
        }
        catch (MySqlException ex) when (ex.ErrorCode == MySqlErrorCode.DuplicateKeyEntry)
        {
            // The same id was saved concurrently; the other request won and this one rolled back.
            var winner = await TryLoadAsync(request.Id, ct);
            if (winner is null)
                throw;
            return new CartCancellationResult(winner, Replayed: true);
        }
    }

    private async Task<CartCancellationDto> CreateWithinAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, CartCancellationRequest request, string reason,
        Guid deviceId, Guid userId, PermissionSet permissions, CancellationToken ct)
    {
        var shift = await c.QuerySingleOrDefaultAsync<(Guid Id, Guid CashierId, string Number)?>(new CommandDefinition(
            "SELECT id, cashier_id, number FROM cashier_shifts WHERE device_id = @deviceId AND node_id = @nodeId AND status = @open FOR SHARE",
            new { deviceId, nodeId = node.Id, open = ShiftStatus.Open }, tx, cancellationToken: ct))
            ?? throw ApiException.Conflict("no_open_shift", $"Device {deviceId} has no open shift.");
        if (shift.CashierId != userId && !permissions.Has(Permissions.ShiftShare))
            throw new ApiException(StatusCodes.Status403Forbidden, "not_shift_owner",
                $"Shift {shift.Number} belongs to another cashier; close it and open your own shift.");

        var unitIds = request.Lines!.Select(l => l.ProductUnitId).Distinct().ToList();
        var products = (await c.QueryAsync<(Guid UnitId, Guid ProductId)>(new CommandDefinition(
            "SELECT id, product_id FROM product_units WHERE id IN @unitIds", new { unitIds }, tx, cancellationToken: ct)))
            .ToDictionary(r => r.UnitId, r => r.ProductId);
        var missing = unitIds.FirstOrDefault(id => !products.ContainsKey(id));
        if (missing != Guid.Empty)
            throw ApiException.Unprocessable("unknown_product_unit", $"Product unit {missing} does not exist.");

        var now = clock.GetUtcNow().UtcDateTime;
        var number = await DocumentNumbering.NextAsync(c, tx, node, DocumentTypes.CartCancellation, now, ct);

        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO cart_cancellations (id, node_id, number, shift_id, device_id, cashier_id, cancelled_at, reason, total_amount)
            VALUES (@Id, @nodeId, @number, @shiftId, @deviceId, @userId, @now, @reason, @TotalAmount)
            """,
            new { request.Id, nodeId = node.Id, number, shiftId = shift.Id, deviceId, userId, now, reason, request.TotalAmount },
            tx, cancellationToken: ct));
        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO cart_cancellation_lines (id, cart_cancellation_id, line_no, product_id, product_unit_id, qty, unit_price, line_total)
            VALUES (@Id, @cancellationId, @LineNo, @ProductId, @ProductUnitId, @Qty, @UnitPrice, @LineTotal)
            """,
            request.Lines!.Select((l, i) => new
            {
                Id = Guid.CreateVersion7(), cancellationId = request.Id, LineNo = i + 1, ProductId = products[l.ProductUnitId],
                l.ProductUnitId, l.Qty, l.UnitPrice, l.LineTotal,
            }).ToList(), tx, cancellationToken: ct));

        var dto = await LoadAsync(c, tx, request.Id, ct) ?? throw new InvalidOperationException("Cancellation not found after insert.");
        await OutboxWriter.WriteAsync(c, tx, SyncDocTypes.CartCancellation, dto.Id, 1, dto, ct);
        return dto;
    }

    private async Task<CartCancellationDto?> TryLoadAsync(Guid id, CancellationToken ct)
    {
        await using var c = await runner.ConnectionFactory.OpenAsync(ct);
        return await LoadAsync(c, null, id, ct);
    }

    private static async Task<CartCancellationDto?> LoadAsync(MySqlConnection c, MySqlTransaction? tx, Guid id, CancellationToken ct)
    {
        var header = await c.QuerySingleOrDefaultAsync<Header>(new CommandDefinition(
            """
            SELECT id AS Id, node_id AS NodeId, number AS Number, shift_id AS ShiftId, device_id AS DeviceId, cashier_id AS CashierId,
                   cancelled_at AS CancelledAt, reason AS Reason, total_amount AS TotalAmount
            FROM cart_cancellations WHERE id = @id
            """, new { id }, tx, cancellationToken: ct));
        if (header is null)
            return null;

        var lines = (await c.QueryAsync<Line>(new CommandDefinition(
            """
            SELECT id AS Id, line_no AS LineNo, product_id AS ProductId, product_unit_id AS ProductUnitId,
                   qty AS Qty, unit_price AS UnitPrice, line_total AS LineTotal
            FROM cart_cancellation_lines WHERE cart_cancellation_id = @id ORDER BY line_no
            """, new { id }, tx, cancellationToken: ct)))
            .Select(l => new CartCancellationLineDto(l.Id, l.LineNo, l.ProductId, l.ProductUnitId, l.Qty, l.UnitPrice, l.LineTotal))
            .ToList();

        return new CartCancellationDto(header.Id, header.NodeId, header.Number, header.ShiftId, header.DeviceId, header.CashierId,
            header.CancelledAt, header.Reason, header.TotalAmount, lines);
    }

    private sealed record Header(
        Guid Id, Guid NodeId, string Number, Guid ShiftId, Guid DeviceId, Guid CashierId, DateTime CancelledAt, string Reason,
        decimal TotalAmount);

    private sealed record Line(Guid Id, short LineNo, Guid ProductId, Guid ProductUnitId, decimal Qty, decimal UnitPrice, decimal LineTotal);
}
