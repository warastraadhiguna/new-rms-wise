/// <summary>One entered line: a product unit and the quantity in that unit (e.g. 2 BOX).</summary>
public sealed record LocationTransferLineRequest(Guid ProductUnitId, decimal Qty);

/// <param name="Id">UUID v7 created by the client; sending it again returns the stored transfer.</param>
public sealed record CreateLocationTransferRequest(
    Guid Id, Guid FromLocationId, Guid ToLocationId, IReadOnlyList<LocationTransferLineRequest>? Lines, string? Notes = null);

public sealed record LocationTransferPreviewRequest(Guid FromLocationId, IReadOnlyList<LocationTransferLineRequest>? Lines);

public sealed record ExpiryQtyDto(DateOnly? ExpiryDate, decimal BaseQty);

/// <summary>What saving would take from the source, per entered line (FEFO, expired stock is not moved).</summary>
/// <param name="StockAtSource">All stock of the product at the source (base unit), expired included.</param>
/// <param name="Available">Stock that FEFO may move (not expired), before this line.</param>
/// <param name="Shortage">How much of the line the source does not have (moved anyway; the source goes negative).</param>
public sealed record LocationTransferPreviewLineDto(
    int LineNo, Guid ProductId, Guid ProductUnitId, decimal Qty, decimal BaseQty, string BaseUnitCode,
    decimal StockAtSource, decimal Available, decimal Shortage, IReadOnlyList<ExpiryQtyDto> Allocations);

public sealed record LocationTransferPreviewDto(DateOnly Today, IReadOnlyList<LocationTransferPreviewLineDto> Lines);

public sealed record LocationTransferLineDto(
    int LineNo, Guid ProductId, string Sku, string Name, Guid? ProductUnitId, string UnitCode, decimal? Qty,
    string BaseUnitCode, decimal BaseQty, IReadOnlyList<ExpiryQtyDto> Expiries);

/// <param name="TransferredAt">UTC.</param>
public sealed record LocationTransferDto(
    Guid Id,
    Guid NodeId,
    string Number,
    Guid FromLocationId,
    string FromLocationCode,
    Guid ToLocationId,
    string ToLocationCode,
    DateTime TransferredAt,
    string TimeZone,
    string? Notes,
    Guid CreatedBy,
    string CreatedByName,
    IReadOnlyList<LocationTransferLineDto> Lines);

public sealed record LocationTransferResult(LocationTransferDto Transfer, bool Replayed);

/// <param name="TimeZone">Branch timezone for showing <c>TransferredAt</c>.</param>
public sealed record LocationTransferSummaryDto(
    Guid Id, string Number, DateTime TransferredAt, string FromLocationCode, string ToLocationCode, string CreatedByName,
    int LineCount, string? Notes, string TimeZone);

/// <summary>
/// "Form Mutasi Lokasi": moves stock between two locations of this node (e.g. STORAGE → DISPLAY). FEFO out of the
/// source keeps each expiry at the destination; one <c>location_transfer_lines</c> row per expiry, ledger rows point
/// at it. Number MT, outbox row, client id (idempotent like sales). Negative source stock is allowed.
/// </summary>
public sealed class LocationTransferService(TransactionRunner runner, NodeIdentity nodeIdentity, TimeProvider clock)
{
    public async Task<LocationTransferResult> CreateAsync(CreateLocationTransferRequest request, Guid userId, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Id.Version != 7)
            throw ApiException.Unprocessable("invalid_id", "The id must be a UUID v7 generated by the client.");
        if (request.Lines is not { Count: > 0 })
            throw ApiException.Unprocessable("no_lines", "Add at least one product.");
        if (request.Lines.Any(l => l.Qty <= 0))
            throw ApiException.Unprocessable("invalid_quantity", "Quantities must be greater than zero.");
        if (request.FromLocationId == request.ToLocationId)
            throw ApiException.Unprocessable("same_location", "The source and destination location must differ.");

        var node = await nodeIdentity.GetAsync(ct);
        if (await TryLoadAsync(request.Id, ct) is { } stored)
            return new LocationTransferResult(stored, Replayed: true);

        try
        {
            var created = await runner.RunAsync((c, tx, token) => CreateWithinAsync(c, tx, node, request, userId, token),
                "Location transfer", ct);
            return new LocationTransferResult(created, Replayed: false);
        }
        catch (MySqlException ex) when (ex.ErrorCode == MySqlErrorCode.DuplicateKeyEntry)
        {
            // The same id was saved concurrently; the other request won and this one rolled back.
            var winner = await TryLoadAsync(request.Id, ct);
            if (winner is null)
                throw;
            return new LocationTransferResult(winner, Replayed: true);
        }
    }

    private async Task<LocationTransferDto> CreateWithinAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, CreateLocationTransferRequest request, Guid userId, CancellationToken ct)
    {
        await EnsureLocationAsync(c, tx, node, request.FromLocationId, "from_location_id", ct);
        await EnsureLocationAsync(c, tx, node, request.ToLocationId, "to_location_id", ct);
        var units = await ResolveLinesAsync(c, tx, request.Lines!, ct);
        var now = clock.GetUtcNow().UtcDateTime;

        var requests = units.Select(u => new StockTransferRequest(node.Id, u.ProductId, request.FromLocationId, request.ToLocationId,
            u.BaseQty, request.Id, null, now)).ToList();
        var moved = await StockPostingService.TransferWithinAsync(c, tx, requests, ct);

        var number = await DocumentNumbering.NextAsync(c, tx, node, DocumentTypes.LocationTransfer, now, ct);
        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO location_transfers (id, node_id, number, from_location_id, to_location_id, transferred_at, notes, created_by)
            VALUES (@Id, @nodeId, @number, @FromLocationId, @ToLocationId, @now, @notes, @userId)
            """,
            new
            {
                request.Id, nodeId = node.Id, number, request.FromLocationId, request.ToLocationId, now,
                notes = string.IsNullOrWhiteSpace(request.Notes) ? null : request.Notes.Trim(), userId,
            }, tx, cancellationToken: ct));

        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO location_transfer_lines (id, location_transfer_id, line_no, product_id, product_unit_id, qty, expiry_date, base_qty)
            VALUES (@Id, @transferId, @LineNo, @ProductId, @ProductUnitId, @Qty, @ExpiryDate, @BaseQty)
            """,
            moved.SelectMany((lines, i) => lines.Select(l => new
            {
                Id = l.LineId, transferId = request.Id, LineNo = i + 1, units[i].ProductId, units[i].ProductUnitId, units[i].Qty,
                ExpiryDate = l.ExpiryDate is { } e ? e.ToDateTime(TimeOnly.MinValue) : (DateTime?)null, l.BaseQty,
            })).ToList(), tx, cancellationToken: ct));

        var transfer = await LoadAsync(c, tx, request.Id, ct)
            ?? throw new InvalidOperationException($"Location transfer {request.Id} was not found after insert.");
        await OutboxWriter.WriteAsync(c, tx, SyncDocTypes.LocationTransfer, request.Id, 1, transfer, ct);
        return transfer;
    }

    /// <summary>FEFO preview from the current stock (no locks, nothing written). Lines are applied in order.</summary>
    public async Task<LocationTransferPreviewDto> PreviewAsync(LocationTransferPreviewRequest request, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        var node = await nodeIdentity.GetAsync(ct);
        var today = BranchClock.Today(clock.GetUtcNow().UtcDateTime, node.TimeZone);
        await using var c = await runner.ConnectionFactory.OpenAsync(ct);
        await EnsureLocationAsync(c, null, node, request.FromLocationId, "from_location_id", ct);
        if (request.Lines is not { Count: > 0 })
            return new LocationTransferPreviewDto(today, []);
        if (request.Lines.Any(l => l.Qty <= 0))
            throw ApiException.Unprocessable("invalid_quantity", "Quantities must be greater than zero.");

        var units = await ResolveLinesAsync(c, null, request.Lines, ct);
        var productIds = units.Select(u => u.ProductId).Distinct().ToList();
        var buckets = (await c.QueryAsync<(Guid ProductId, DateTime ExpiryKey, decimal Qty)>(new CommandDefinition(
            "SELECT product_id, expiry_key, base_qty FROM stock_balances WHERE location_id = @FromLocationId AND product_id IN @productIds",
            new { request.FromLocationId, productIds }, cancellationToken: ct))).ToList();
        IReadOnlyDictionary<StockBalanceKey, decimal> balances = buckets.ToDictionary(
            b => new StockBalanceKey(request.FromLocationId, b.ProductId, StockExpiryKey.FromKey(DateOnly.FromDateTime(b.ExpiryKey))),
            b => b.Qty);

        var lines = new List<LocationTransferPreviewLineDto>();
        for (var i = 0; i < units.Count; i++)
        {
            var u = units[i];
            var productBuckets = StockBalances.BucketsFor(balances, request.FromLocationId, u.ProductId);
            var stock = productBuckets.Sum(b => b.BaseQty);
            var available = productBuckets.Where(b => b.BaseQty > 0 && (b.ExpiryDate is null || b.ExpiryDate >= today)).Sum(b => b.BaseQty);
            var allocations = StockAllocator.AllocateOutbound(productBuckets, u.BaseQty, u.TrackExpiry, today);
            lines.Add(new LocationTransferPreviewLineDto(i + 1, u.ProductId, u.ProductUnitId, u.Qty, u.BaseQty, u.BaseUnitCode,
                stock, available, Math.Max(0m, u.BaseQty - available),
                allocations.Select(a => new ExpiryQtyDto(a.ExpiryDate, a.BaseQty)).ToList()));

            // later lines of the same product see this one
            balances = StockBalances.Apply(balances, allocations.Select(a => new StockLedgerEntry(Guid.Empty, node.Id,
                request.FromLocationId, u.ProductId, a.ExpiryDate, -a.BaseQty, StockDocTypes.LocationTransfer, Guid.Empty, null, DateTime.UtcNow)));
        }
        return new LocationTransferPreviewDto(today, lines);
    }

    /// <summary>Daftar Mutasi Lokasi: this node's transfers in branch dates from..to (newest first).</summary>
    public async Task<IReadOnlyList<LocationTransferSummaryDto>> ListAsync(DateOnly from, DateOnly to, CancellationToken ct = default)
    {
        if (to < from)
            throw ApiException.Unprocessable("invalid_range", "The end date is before the start date.");
        var node = await nodeIdentity.GetAsync(ct);
        var (fromUtc, toUtc) = BranchClock.DayRangeUtc(from, to, TimeZoneInfo.FindSystemTimeZoneById(node.TimeZone));
        await using var c = await runner.ConnectionFactory.OpenAsync(ct);
        var rows = await c.QueryAsync<SummaryRow>(new CommandDefinition(
            """
            SELECT t.id AS Id, t.number AS Number, t.transferred_at AS TransferredAt, lf.code AS FromLocationCode,
                   lt.code AS ToLocationCode, u.full_name AS CreatedByName,
                   (SELECT COUNT(DISTINCT line_no) FROM location_transfer_lines x WHERE x.location_transfer_id = t.id) AS LineCount,
                   t.notes AS Notes
            FROM location_transfers t
            JOIN locations lf ON lf.id = t.from_location_id
            JOIN locations lt ON lt.id = t.to_location_id
            JOIN users u ON u.id = t.created_by
            WHERE t.node_id = @nodeId AND t.transferred_at >= @fromUtc AND t.transferred_at < @toUtc
            ORDER BY t.transferred_at DESC, t.number DESC
            """, new { nodeId = node.Id, fromUtc, toUtc }, cancellationToken: ct));
        return rows.Select(r => new LocationTransferSummaryDto(r.Id, r.Number, DateTime.SpecifyKind(r.TransferredAt, DateTimeKind.Utc),
            r.FromLocationCode, r.ToLocationCode, r.CreatedByName, (int)r.LineCount, r.Notes, node.TimeZone)).ToList();
    }

    public async Task<LocationTransferDto> GetAsync(Guid id, CancellationToken ct = default) =>
        await TryLoadAsync(id, ct) ?? throw ApiException.NotFound("unknown_transfer", $"Location transfer {id} does not exist at this node.");

    private async Task<LocationTransferDto?> TryLoadAsync(Guid id, CancellationToken ct)
    {
        await using var c = await runner.ConnectionFactory.OpenAsync(ct);
        return await LoadAsync(c, null, id, ct);
    }

    private static async Task<LocationTransferDto?> LoadAsync(MySqlConnection c, MySqlTransaction? tx, Guid id, CancellationToken ct)
    {
        var h = await c.QuerySingleOrDefaultAsync<HeaderRow>(new CommandDefinition(
            """
            SELECT t.id AS Id, t.node_id AS NodeId, t.number AS Number, t.from_location_id AS FromLocationId, lf.code AS FromLocationCode,
                   t.to_location_id AS ToLocationId, lt.code AS ToLocationCode, t.transferred_at AS TransferredAt, b.timezone AS TimeZone,
                   t.notes AS Notes, t.created_by AS CreatedBy, u.full_name AS CreatedByName
            FROM location_transfers t
            JOIN locations lf ON lf.id = t.from_location_id
            JOIN locations lt ON lt.id = t.to_location_id
            JOIN nodes n ON n.id = t.node_id
            JOIN branches b ON b.id = n.branch_id
            JOIN users u ON u.id = t.created_by
            WHERE t.id = @id
            """, new { id }, tx, cancellationToken: ct));
        if (h is null)
            return null;

        var rows = (await c.QueryAsync<LineRow>(new CommandDefinition(
            """
            SELECT l.line_no AS LineNo, l.product_id AS ProductId, p.sku AS Sku, p.name AS Name, l.product_unit_id AS ProductUnitId,
                   COALESCE(u.code, bu.code) AS UnitCode, l.qty AS Qty, bu.code AS BaseUnitCode, l.expiry_date AS ExpiryDate,
                   l.base_qty AS BaseQty
            FROM location_transfer_lines l
            JOIN products p ON p.id = l.product_id
            JOIN units bu ON bu.id = p.base_unit_id
            LEFT JOIN product_units pu ON pu.id = l.product_unit_id
            LEFT JOIN units u ON u.id = pu.unit_id
            WHERE l.location_transfer_id = @id
            ORDER BY l.line_no, l.expiry_date IS NULL, l.expiry_date
            """, new { id }, tx, cancellationToken: ct))).ToList();

        var lines = rows.GroupBy(r => r.LineNo).Select(g =>
        {
            var first = g.First();
            return new LocationTransferLineDto(first.LineNo, first.ProductId, first.Sku, first.Name, first.ProductUnitId,
                first.UnitCode, first.Qty, first.BaseUnitCode, g.Sum(r => r.BaseQty),
                g.Select(r => new ExpiryQtyDto(r.ExpiryDate is { } e ? DateOnly.FromDateTime(e) : null, r.BaseQty)).ToList());
        }).ToList();

        return new LocationTransferDto(h.Id, h.NodeId, h.Number, h.FromLocationId, h.FromLocationCode, h.ToLocationId, h.ToLocationCode,
            DateTime.SpecifyKind(h.TransferredAt, DateTimeKind.Utc), h.TimeZone, h.Notes, h.CreatedBy, h.CreatedByName, lines);
    }

    private static async Task EnsureLocationAsync(
        MySqlConnection c, MySqlTransaction? tx, NodeInfo node, Guid locationId, string field, CancellationToken ct)
    {
        var exists = await c.ExecuteScalarAsync<int>(new CommandDefinition(
            "SELECT COUNT(*) FROM locations WHERE id = @locationId AND node_id = @nodeId AND deleted_at IS NULL",
            new { locationId, nodeId = node.Id }, tx, cancellationToken: ct)) > 0;
        if (!exists)
            throw ApiException.Unprocessable("unknown_location", $"{field}: location {locationId} is not a location of node {node.Code}.");
    }

    /// <summary>Entered lines → product, base quantity (unit conversion, whole numbers for whole units).</summary>
    private static async Task<IReadOnlyList<ResolvedLine>> ResolveLinesAsync(
        MySqlConnection c, MySqlTransaction? tx, IReadOnlyList<LocationTransferLineRequest> lines, CancellationToken ct)
    {
        var unitIds = lines.Select(l => l.ProductUnitId).Distinct().ToList();
        var units = (await c.QueryAsync<UnitRow>(new CommandDefinition(
            """
            SELECT pu.id AS ProductUnitId, pu.product_id AS ProductId, pu.conversion AS Conversion, u.allow_decimal AS AllowDecimal,
                   p.track_expiry AS TrackExpiry, bu.code AS BaseUnitCode
            FROM product_units pu
            JOIN units u ON u.id = pu.unit_id
            JOIN products p ON p.id = pu.product_id
            JOIN units bu ON bu.id = p.base_unit_id
            WHERE pu.id IN @unitIds AND pu.deleted_at IS NULL AND p.deleted_at IS NULL
            """, new { unitIds }, tx, cancellationToken: ct))).ToDictionary(u => u.ProductUnitId);

        return lines.Select(l =>
        {
            if (!units.TryGetValue(l.ProductUnitId, out var unit))
                throw ApiException.Unprocessable("unknown_product_unit", $"Product unit {l.ProductUnitId} does not exist.");
            try
            {
                return new ResolvedLine(unit.ProductId, unit.ProductUnitId, l.Qty,
                    UnitConversion.ToBaseQty(l.Qty, unit.Conversion, unit.AllowDecimal), unit.TrackExpiry, unit.BaseUnitCode);
            }
            catch (InvalidQuantityException ex)
            {
                throw ApiException.Unprocessable("invalid_quantity", ex.Message);
            }
        }).ToList();
    }

    private sealed record ResolvedLine(Guid ProductId, Guid ProductUnitId, decimal Qty, decimal BaseQty, bool TrackExpiry, string BaseUnitCode);

    private sealed record UnitRow(Guid ProductUnitId, Guid ProductId, decimal Conversion, bool AllowDecimal, bool TrackExpiry, string BaseUnitCode);

    private sealed record HeaderRow(
        Guid Id, Guid NodeId, string Number, Guid FromLocationId, string FromLocationCode, Guid ToLocationId, string ToLocationCode,
        DateTime TransferredAt, string TimeZone, string? Notes, Guid CreatedBy, string CreatedByName);

    private sealed record LineRow(
        short LineNo, Guid ProductId, string Sku, string Name, Guid? ProductUnitId, string UnitCode, decimal? Qty, string BaseUnitCode,
        DateTime? ExpiryDate, decimal BaseQty);

    private sealed record SummaryRow(
        Guid Id, string Number, DateTime TransferredAt, string FromLocationCode, string ToLocationCode, string CreatedByName, long LineCount,
        string? Notes);
}
