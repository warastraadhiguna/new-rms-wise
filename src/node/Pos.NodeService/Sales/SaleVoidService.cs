namespace Pos.NodeService.Sales;

/// <param name="Id">UUID v7 from the client (a retry with the same id returns the stored void).</param>
/// <param name="ApprovalToken">Supervisor approval (action sale.void) when the user lacks sale.void.</param>
public sealed record VoidSaleRequest(Guid Id, Guid ReasonId, string? Notes, string? ApprovalToken = null);

public sealed record SaleVoidDto(
    Guid Id,
    Guid NodeId,
    Guid SaleId,
    string SaleNumber,
    Guid ReasonId,
    string ReasonName,
    string Notes,
    DateTime VoidedAt,
    Guid CreatedBy,
    string CreatedByName,
    Guid? ApprovedBy,
    string? ApprovedByName);

public sealed record SaleVoidResult(SaleVoidDto Void, bool Replayed);

/// <summary>A reason from the master list (SALE_VOID, RETURN, ADJUSTMENT).</summary>
public sealed record ReasonDto(Guid Id, string Type, string Name);

public static class ReasonTypes
{
    public const string SaleVoid = "SALE_VOID";
    public const string Return = "RETURN";
}

/// <summary>
/// Void of a sale whose shift is still open (otherwise: a return). Reason (SALE_VOID) and notes are required; a user
/// without <c>sale.void</c> needs a supervisor's approval. The sale row is never changed: the void is its own row,
/// every sold quantity goes back into the bucket it came from (ledger SALE_VOID), loyalty points of the sale are
/// cancelled, and its receivable no longer counts (voided sales are left out everywhere). One void per sale; idempotent.
/// </summary>
public sealed class SaleVoidService(TransactionRunner runner, NodeIdentity nodeIdentity, TimeProvider clock)
{
    public async Task<SaleVoidResult> VoidAsync(Guid saleId, VoidSaleRequest request, Guid userId, bool canVoid, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Id.Version != 7)
            throw ApiException.Unprocessable("invalid_id", "The void id must be a UUID v7 generated by the client.");
        var notes = request.Notes?.Trim();
        if (string.IsNullOrEmpty(notes))
            throw ApiException.Unprocessable("reason_required", "Notes are required to void a sale.");

        var node = await nodeIdentity.GetAsync(cancellationToken);
        try
        {
            return await runner.RunAsync((c, tx, ct) => VoidWithinAsync(c, tx, node, saleId, request, notes, userId, canVoid, ct),
                "Void sale", cancellationToken);
        }
        catch (MySqlException ex) when (ex.ErrorCode == MySqlErrorCode.DuplicateKeyEntry)
        {
            // The same sale was voided concurrently: the stored void answers (or says it is someone else's).
            await using var c = await runner.ConnectionFactory.OpenAsync(cancellationToken);
            var stored = await LoadBySaleAsync(c, null, saleId, cancellationToken);
            if (stored is null)
                throw;
            if (stored.Id != request.Id)
                throw AlreadyVoided(stored);
            return new SaleVoidResult(stored, Replayed: true);
        }
    }

    private async Task<SaleVoidResult> VoidWithinAsync(
        MySqlConnection c, MySqlTransaction tx, NodeInfo node, Guid saleId, VoidSaleRequest request, string notes, Guid userId,
        bool canVoid, CancellationToken ct)
    {
        if (await LoadBySaleAsync(c, tx, saleId, ct) is { } existing)
        {
            if (existing.Id != request.Id)
                throw AlreadyVoided(existing);
            return new SaleVoidResult(existing, Replayed: true);
        }

        // Shared lock on the shift: a shift close (FOR UPDATE) waits until this void commits, and sees it.
        var sale = await c.QuerySingleOrDefaultAsync<SaleRow>(new CommandDefinition(
            """
            SELECT s.id AS Id, s.node_id AS NodeId, s.number AS Number, cs.status AS ShiftStatus, cs.number AS ShiftNumber
            FROM sales s JOIN cashier_shifts cs ON cs.id = s.shift_id
            WHERE s.id = @saleId
            FOR SHARE
            """, new { saleId }, tx, cancellationToken: ct));
        if (sale is null || sale.NodeId != node.Id)
            throw ApiException.NotFound("unknown_sale", $"Sale {saleId} does not exist at this node.");
        if (sale.ShiftStatus != ShiftStatus.Open)
            throw ApiException.Conflict("shift_closed", $"Shift {sale.ShiftNumber} of sale {sale.Number} is closed; use a return.");
        if (await c.ExecuteScalarAsync<long>(new CommandDefinition(
                "SELECT COUNT(*) FROM sale_returns WHERE sale_id = @saleId", new { saleId }, tx, cancellationToken: ct)) > 0)
            throw ApiException.Conflict("has_returns", $"Sale {sale.Number} already has returns; it cannot be voided.");
        if (await c.ExecuteScalarAsync<long>(new CommandDefinition(
                "SELECT COUNT(*) FROM reasons WHERE id = @ReasonId AND type = @type AND deleted_at IS NULL",
                new { request.ReasonId, type = ReasonTypes.SaleVoid }, tx, cancellationToken: ct)) == 0)
            throw ApiException.Unprocessable("unknown_reason", "The reason is not a void reason (SALE_VOID).");

        var now = clock.GetUtcNow().UtcDateTime;
        Guid? approvedBy = null;
        if (!canVoid)
        {
            if (string.IsNullOrWhiteSpace(request.ApprovalToken))
                throw new ApiException(StatusCodes.Status403Forbidden, "void_approval_required",
                    "Voiding a sale needs permission sale.void or a supervisor's approval.");
            approvedBy = await ApprovalTokens.ConsumeAsync(c, tx, request.ApprovalToken, Permissions.SaleVoid, userId, request.Id, now, ct)
                ?? throw new ApiException(StatusCodes.Status403Forbidden, "invalid_approval",
                    "The approval token is unknown, expired, already used, or not for this action or user.");
        }

        await c.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO sale_voids (id, node_id, sale_id, reason_id, notes, approved_by, voided_at, created_by)
            VALUES (@Id, @nodeId, @saleId, @ReasonId, @notes, @approvedBy, @now, @userId)
            """, new { request.Id, nodeId = node.Id, saleId, request.ReasonId, notes, approvedBy, now, userId }, tx, cancellationToken: ct));

        // Stock back into the buckets the sale took (same location, product and expiry).
        var sold = (await c.QueryAsync<LedgerRow>(new CommandDefinition(
            """
            SELECT id AS Id, node_id AS NodeId, location_id AS LocationId, product_id AS ProductId, expiry_date AS ExpiryDate,
                   base_qty AS BaseQty, doc_line_id AS DocLineId
            FROM stock_ledger WHERE doc_type = @sale AND doc_id = @saleId
            """, new { sale = StockDocTypes.Sale, saleId }, tx, cancellationToken: ct)))
            .Select(r => new StockLedgerEntry(r.Id, r.NodeId, r.LocationId, r.ProductId,
                r.ExpiryDate is { } e ? DateOnly.FromDateTime(e) : null, r.BaseQty, StockDocTypes.Sale, saleId, r.DocLineId, now))
            .ToList();
        var movements = StockReversal.ReverseOutbound(sold)
            .Select(m => new StockMovement(
                new StockDocumentLine(node.Id, m.LocationId, m.ProductId, StockDocTypes.SaleVoid, request.Id, m.DocLineId, now),
                StockDirection.In, m.BaseQty, m.ExpiryDate))
            .ToList();
        if (movements.Count > 0)
            await StockPostingService.PostWithinAsync(c, tx, movements, ct);

        // Loyalty points earned (or redeemed) on the sale are cancelled.
        var points = await c.QueryAsync<(Guid CustomerId, decimal Points)>(new CommandDefinition(
            """
            SELECT customer_id, SUM(points) FROM loyalty_point_ledger WHERE doc_type = @sale AND doc_id = @saleId
            GROUP BY customer_id HAVING SUM(points) <> 0
            """, new { sale = StockDocTypes.Sale, saleId }, tx, cancellationToken: ct));
        foreach (var (customerId, sum) in points)
        {
            await c.ExecuteAsync(new CommandDefinition(
                """
                INSERT INTO loyalty_point_ledger (id, node_id, customer_id, points, doc_type, doc_id, occurred_at)
                VALUES (@id, @nodeId, @customerId, @points, @type, @voidId, @now)
                """, new { id = Guid.CreateVersion7(), nodeId = node.Id, customerId, points = -(int)sum, type = StockDocTypes.SaleVoid, voidId = request.Id, now },
                tx, cancellationToken: ct));
        }

        var dto = await LoadBySaleAsync(c, tx, saleId, ct) ?? throw new InvalidOperationException("The void was not stored.");
        await OutboxWriter.WriteAsync(c, tx, SyncDocTypes.SaleVoid, dto.Id, 1, dto, ct);
        return new SaleVoidResult(dto, Replayed: false);
    }

    public async Task<IReadOnlyList<ReasonDto>> ReasonsAsync(string type, CancellationToken ct = default)
    {
        await using var c = await runner.ConnectionFactory.OpenAsync(ct);
        return (await c.QueryAsync<ReasonDto>(new CommandDefinition(
            "SELECT id AS Id, type AS Type, name AS Name FROM reasons WHERE type = @type AND deleted_at IS NULL ORDER BY name",
            new { type }, cancellationToken: ct))).ToList();
    }

    private static ApiException AlreadyVoided(SaleVoidDto existing) =>
        ApiException.Conflict("already_voided", $"Sale {existing.SaleNumber} is already voided.");

    internal static async Task<SaleVoidDto?> LoadBySaleAsync(MySqlConnection c, MySqlTransaction? tx, Guid saleId, CancellationToken ct)
    {
        var row = await c.QuerySingleOrDefaultAsync<VoidRow>(new CommandDefinition(
            """
            SELECT v.id AS Id, v.node_id AS NodeId, v.sale_id AS SaleId, s.number AS SaleNumber, v.reason_id AS ReasonId,
                   r.name AS ReasonName, v.notes AS Notes, v.voided_at AS VoidedAt, v.created_by AS CreatedBy,
                   u.full_name AS CreatedByName, v.approved_by AS ApprovedBy, a.full_name AS ApprovedByName
            FROM sale_voids v
            JOIN sales s ON s.id = v.sale_id
            JOIN reasons r ON r.id = v.reason_id
            JOIN users u ON u.id = v.created_by
            LEFT JOIN users a ON a.id = v.approved_by
            WHERE v.sale_id = @saleId
            """, new { saleId }, tx, cancellationToken: ct));
        return row is null ? null : new SaleVoidDto(row.Id, row.NodeId, row.SaleId, row.SaleNumber, row.ReasonId, row.ReasonName,
            row.Notes ?? "", DateTime.SpecifyKind(row.VoidedAt, DateTimeKind.Utc), row.CreatedBy, row.CreatedByName, row.ApprovedBy,
            row.ApprovedByName);
    }

    private sealed class SaleRow
    {
        public Guid Id { get; set; }
        public Guid NodeId { get; set; }
        public string Number { get; set; } = "";
        public string ShiftStatus { get; set; } = "";
        public string ShiftNumber { get; set; } = "";
    }

    private sealed class LedgerRow
    {
        public Guid Id { get; set; }
        public Guid NodeId { get; set; }
        public Guid LocationId { get; set; }
        public Guid ProductId { get; set; }
        public DateTime? ExpiryDate { get; set; }
        public decimal BaseQty { get; set; }
        public Guid? DocLineId { get; set; }
    }

    private sealed class VoidRow
    {
        public Guid Id { get; set; }
        public Guid NodeId { get; set; }
        public Guid SaleId { get; set; }
        public string SaleNumber { get; set; } = "";
        public Guid ReasonId { get; set; }
        public string ReasonName { get; set; } = "";
        public string? Notes { get; set; }
        public DateTime VoidedAt { get; set; }
        public Guid CreatedBy { get; set; }
        public string CreatedByName { get; set; } = "";
        public Guid? ApprovedBy { get; set; }
        public string? ApprovedByName { get; set; }
    }
}
