    private static async Task<SaleDto?> LoadAsync(MySqlConnection c, MySqlTransaction? tx, Guid id, CancellationToken ct)
    {
        var header = await c.QuerySingleOrDefaultAsync<HeaderRow>(new CommandDefinition(
            """
            SELECT id AS Id, node_id AS NodeId, number AS Number, shift_id AS ShiftId, customer_id AS CustomerId,
                   sold_at AS SoldAt, subtotal AS Subtotal, discount_amount AS DiscountAmount, tax_amount AS TaxAmount,
                   rounding_amount AS RoundingAmount, total AS Total, credit_amount AS CreditAmount,
                   due_date AS DueDate, notes AS Notes, created_by AS CreatedBy
            FROM sales WHERE id = @id
            """, new { id }, tx, cancellationToken: ct));
        if (header is null)
            return null;

        var lines = (await c.QueryAsync<LineRow>(new CommandDefinition(
            """
            SELECT id AS Id, line_no AS LineNo, product_id AS ProductId, product_unit_id AS ProductUnitId, location_id AS LocationId,
                   qty AS Qty, conversion AS Conversion, base_qty AS BaseQty, unit_price AS UnitPrice,
                   discount_amount AS DiscountAmount, tax_amount AS TaxAmount, line_total AS LineTotal
            FROM sale_lines WHERE sale_id = @id ORDER BY line_no
            """, new { id }, tx, cancellationToken: ct))).ToList();

        var stock = (await c.QueryAsync<StockRow>(new CommandDefinition(
            """
            SELECT doc_line_id AS DocLineId, expiry_date AS ExpiryDate, -base_qty AS BaseQty
            FROM stock_ledger WHERE doc_type = 'SALE' AND doc_id = @id
            ORDER BY expiry_date IS NULL, expiry_date
            """, new { id }, tx, cancellationToken: ct))).ToList();

        var payments = (await c.QueryAsync<SalePaymentDto>(new CommandDefinition(
            """
            SELECT sp.id AS Id, pm.code AS Method, sp.amount AS Amount, sp.tendered AS Tendered,
                   sp.change_given AS ChangeGiven, sp.reference AS Reference
            FROM sale_payments sp JOIN payment_methods pm ON pm.id = sp.payment_method_id
            WHERE sp.sale_id = @id ORDER BY pm.is_cash, sp.id
            """, new { id }, tx, cancellationToken: ct))).ToList();

        return new SaleDto(
            header.Id, header.NodeId, header.Number, header.ShiftId, header.CustomerId, header.SoldAt,
            header.Subtotal, header.DiscountAmount, header.TaxAmount, header.RoundingAmount, header.Total, header.CreditAmount,
            payments.Sum(p => p.ChangeGiven ?? 0m),
            header.DueDate is { } due ? DateOnly.FromDateTime(due) : null,
            header.Notes, header.CreatedBy,
            lines.Select(l => new SaleLineDto(l.Id, l.LineNo, l.ProductId, l.ProductUnitId, l.LocationId, l.Qty, l.Conversion,
                l.BaseQty, l.UnitPrice, l.DiscountAmount, l.TaxAmount, l.LineTotal,
                stock.Where(s => s.DocLineId == l.Id)
                    .Select(s => new SaleLineStockDto(s.ExpiryDate is { } e ? DateOnly.FromDateTime(e) : null, s.BaseQty))
                    .ToList())).ToList(),
            payments);
    }

    private sealed record SaleSettings(CashRoundingSettings Rounding, int CurrencyDecimals);

    private sealed record CustomerRow(decimal? CreditLimit, short? PaymentTermDays);

    private sealed record MethodRow(Guid Id, string Code, bool IsCash, bool IsCredit)
    {
        public PaymentKind Kind => IsCash ? PaymentKind.Cash : IsCredit ? PaymentKind.Credit : PaymentKind.NonCash;
    }

    private sealed record UnitRow(Guid ProductId, decimal Conversion, bool AllowDecimal);

    private sealed record ResolvedLine(
        Guid ProductId, Guid ProductUnitId, decimal Qty, decimal Conversion, decimal BaseQty, decimal UnitPrice, SaleLineAmounts Amounts);

    private sealed record HeaderRow(
        Guid Id, Guid NodeId, string Number, Guid ShiftId, Guid? CustomerId, DateTime SoldAt, decimal Subtotal,
        decimal DiscountAmount, decimal TaxAmount, decimal RoundingAmount, decimal Total, decimal CreditAmount,
        DateTime? DueDate, string? Notes, Guid CreatedBy);

    private sealed record LineRow(
        Guid Id, short LineNo, Guid ProductId, Guid ProductUnitId, Guid LocationId, decimal Qty, decimal Conversion,
        decimal BaseQty, decimal UnitPrice, decimal DiscountAmount, decimal TaxAmount, decimal LineTotal);

    private sealed record StockRow(Guid DocLineId, DateTime? ExpiryDate, decimal BaseQty);
}
