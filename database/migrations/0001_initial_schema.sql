) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


-- =====================================================================
-- PART C. NODE DOCUMENTS  (owner: the node in node_id; replicas allowed, read-only)
-- Common columns: node_id, number (unique per node), created_by, created_at, updated_at, row_version
-- =====================================================================

-- Stock ledger: INSERT only. Positive base_qty = in, negative = out.
CREATE TABLE stock_ledger (
  id            CHAR(36) CHARACTER SET ascii NOT NULL,
  node_id       CHAR(36) CHARACTER SET ascii NOT NULL,
  location_id   CHAR(36) CHARACTER SET ascii NOT NULL,
  product_id    CHAR(36) CHARACTER SET ascii NOT NULL,
  expiry_date   DATE          NULL,
  base_qty      DECIMAL(18,4) NOT NULL,
  doc_type      VARCHAR(30)   NOT NULL,                -- SALE | SALE_RETURN | GOODS_RECEIPT | DELIVERY | LOCATION_TRANSFER | ADJUSTMENT
  doc_id        CHAR(36) CHARACTER SET ascii NOT NULL,
  doc_line_id   CHAR(36) CHARACTER SET ascii NULL,
  occurred_at   DATETIME(3)   NOT NULL,
  created_at    DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_stock_ledger_balance (location_id, product_id, expiry_date),
  KEY ix_stock_ledger_product (product_id, occurred_at),
  KEY ix_stock_ledger_doc     (doc_type, doc_id),
  CONSTRAINT fk_sl_node     FOREIGN KEY (node_id)     REFERENCES nodes (id),
  CONSTRAINT fk_sl_location FOREIGN KEY (location_id) REFERENCES locations (id),
  CONSTRAINT fk_sl_product  FOREIGN KEY (product_id)  REFERENCES products (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Balance cache (node-local, rebuilt from stock_ledger any time). expiry_key '9999-12-31' = no expiry.
CREATE TABLE stock_balances (
  location_id   CHAR(36) CHARACTER SET ascii NOT NULL,
  product_id    CHAR(36) CHARACTER SET ascii NOT NULL,
